def replace_paragraph_text(p: etree._Element, new_text: str) -> None:
    """Replace text content of a paragraph with new_text, keeping pPr.

    Removes all <w:r>, <w:hyperlink>, <w:proofErr> children, then appends a
    single fresh <w:r><w:t xml:space="preserve">{new_text}</w:t></w:r>.

    Skips paragraphs that contain a formula or drawing — those are handled
    separately (only label-only paragraphs get full replacement here).
    """
    # Bail out on formula or drawing paragraphs
    for tag in ("object", "drawing", "pict"):
        if p.find(f".//{w(tag)}") is not None:
            raise RuntimeError(
                f"Refusing to overwrite paragraph containing <{tag}> — manual edit required"
            )
    # Strip non-pPr children
    for child in list(p):
        if not child.tag.endswith("}pPr"):
            p.remove(child)
    r = etree.SubElement(p, w("r"))
    t = etree.SubElement(r, w("t"))
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    t.text = new_text


def replace_formula_paragraph(p: etree._Element, blocks: list[str]) -> None:
    """Replace text in a paragraph that contains MathType formulas.

    A "block" is a contiguous run of text-only <w:r> elements between formula
    runs (those containing <w:object>, <w:drawing>, or <w:pict>). The number
    of blocks in a paragraph equals (formula_count + 1); empty boundary
    blocks (e.g. a paragraph that starts with a formula has an empty block 0)
    are still counted and must appear as "" in the translation list.

    For each non-empty block, the first text run carries the translation;
    subsequent runs in the same block have their <w:t> text cleared so Word
    does not render leftover English. Formula/drawing/picture runs are
    untouched.
    """
    runs = p.findall(w("r"))

    text_blocks: list[list[etree._Element]] = []
    current: list[etree._Element] = []
    for r in runs:
        is_formula = (
            r.find(f".//{w('object')}") is not None
            or r.find(f".//{w('drawing')}") is not None
            or r.find(f".//{w('pict')}") is not None
        )
        if is_formula:
            text_blocks.append(current)
            current = []
            continue
        if r.find(w("t")) is None:
            continue
        current.append(r)
    text_blocks.append(current)

    if len(blocks) != len(text_blocks):
        raise RuntimeError(
            f"Translation has {len(blocks)} blocks but paragraph has {len(text_blocks)} text-block slots"
        )

    for i, block in enumerate(text_blocks):
        translation = blocks[i]
        if not block:
            if translation:
                raise RuntimeError(
                    f"Block {i} is empty (no text run before/after formula) but translation is non-empty"
                )
            continue
        first = block[0]
        first_t = first.find(w("t"))
        if first_t is None:
            raise RuntimeError("First run of block has no <w:t> child")
        first_t.text = translation
        first_t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
        for r in block[1:]:
            for t in r.findall(w("t")):
                t.text = ""
                t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")


